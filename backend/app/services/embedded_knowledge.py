def search_embedded_knowledge(query: str, patient_age: str = None) -> str:
    """
    Busca na base de conhecimento embutida
    
    Args:
        query: Texto da pergunta
        patient_age: Idade do paciente (se conhecida): "crianca", "adulto", ou None
        
    Returns:
        Contexto relevante encontrado
    """
    query_lower = query.lower()
    context_parts = []
    
    # Detectar se é para criança ou adulto
    kids_keywords = [
        "criança", "filho", "filha", "bebê", "bebe", "infantil", "kids",
        "odontopediatria", "autismo", "especial", "síndrome", "sindrome",
        "invisalign first", "ortopedia funcional"
    ]
    
    adult_keywords = [
        "adulto", "meu dente", "minha", "implante", "canal", "clareamento",
        "faceta", "prótese", "protese", "invisalign adulto", "ortodontia adulto"
    ]
    
    # Determinar público-alvo
    is_kids = patient_age == "crianca" or any(kw in query_lower for kw in kids_keywords)
    is_adult = patient_age == "adulto" or any(kw in query_lower for kw in adult_keywords)
    
    # Palavras-chave para categorias
    keywords = {
        "apresentacao": ["quem", "vocês", "clinica", "atende", "diferença"],
        "especialidades_kids": kids_keywords,
        "especialidades_adulto": adult_keywords,
        "convenios": ["convênio", "convenio", "plano", "aceita", "unimed", "bradesco"],
        "politicas": ["horário", "horario", "funciona", "cancelar", "pagar", "pagamento"],
        "faq": ["como", "onde", "quando", "estacionamento"]
    }
    
    # Encontrar categorias relevantes
    relevant_categories = []
    
    # Sempre incluir apresentação se não souber o público
    if not is_kids and not is_adult:
        relevant_categories.append("apresentacao")
    
    for category, words in keywords.items():
        if any(word in query_lower for word in words):
            relevant_categories.append(category)
    
    # Se detectou kids, priorizar kids
    if is_kids and "especialidades_kids" not in relevant_categories:
        relevant_categories.insert(0, "especialidades_kids")
    
    # Se detectou adulto, priorizar adulto
    if is_adult and "especialidades_adulto" not in relevant_categories:
        relevant_categories.insert(0, "especialidades_adulto")
    
    # Se não encontrou nada específico, usar apresentação + FAQ
    if not relevant_categories:
        relevant_categories = ["apresentacao", "faq"]
    
    # Montar contexto
    context_parts.append("=== BEM-QUERER ODONTOLOGIA ===\n")
    
    for category in relevant_categories[:3]:  # Máximo 3 categorias
        content = EMBEDDED_KNOWLEDGE.get(category, "")
        if content:
            context_parts.append(content)
            context_parts.append("\n---\n")
    
    return '\n'.join(context_parts)
